import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { createHash, randomUUID } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import { parseEnv } from "node:util";
import { parse, stringify } from "yaml";

function snapshot(root) {
  return readdirSync(root, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((entry) => {
      const path = join(root, entry.name);
      return entry.isDirectory()
        ? snapshot(path)
        : [
            {
              path,
              digest: createHash("sha256").update(readFileSync(path)).digest("hex"),
              mode: statSync(path).mode & 0o777,
            },
          ];
    });
}

/** Exercise the installed executable against disposable, generated projects only. */
export function validateEnvironmentRecovery({ cli, cwd, temporary, runtime = false }) {
  function execute(command, args, project = cwd) {
    const environment = { ...process.env };
    delete environment.COMPOSE_PROJECT_NAME;
    delete environment.COMPOSE_FILE;
    delete environment.COMPOSE_ENV_FILES;
    const result = spawnSync(command, args, {
      cwd: project,
      env: environment,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
      timeout: 120_000,
      maxBuffer: 4 * 1024 * 1024,
    });
    // Never attach child output to an assertion: Compose and CLI output may contain secrets.
    assert.ok(!result.error, `${command} failed to execute`);
    assert.equal(result.signal, null, `${command} was interrupted`);
    return result;
  }
  function docker(args, project) {
    const result = execute("docker", args, project);
    assert.equal(result.status, 0, `Docker ${args[0]} failed`);
    return result.stdout.trim();
  }
  function command(args, expected = 0) {
    const result = execute(process.execPath, [cli, ...args, "--json"]);
    assert.equal(result.status, expected, `CLI ${args.slice(0, 2).join(" ")} exit code`);
    let document;
    try {
      document = JSON.parse(result.stdout);
    } catch {
      assert.fail("CLI did not return valid JSON");
    }
    assert.equal(document.ok, expected === 0, "CLI JSON success matches exit code");
    return document;
  }
  function env(project, name, flags = [], expected = 0) {
    return command(["env", name, project, ...flags], expected);
  }
  function preserve(project, operation) {
    const before = snapshot(project);
    const result = operation();
    assert.deepEqual(snapshot(project), before, "read-only/refused/no-op command changed files");
    return result;
  }
  function values(project, path) {
    return parseEnv(readFileSync(join(project, path), "utf8"));
  }
  function noSecrets(project, paths, document) {
    const output = JSON.stringify(document);
    const privatePaths = new Set([
      ...paths.map((path) => join(project, path)),
      ...snapshot(project)
        .filter((file) => file.path.endsWith(".env"))
        .map((file) => file.path),
    ]);
    for (const path of privatePaths) {
      for (const [key, value] of Object.entries(parseEnv(readFileSync(path, "utf8")))) {
        if (/PASSWORD|SECRET|TOKEN|PRIVATE.*KEY|PRIVATE_JWK$|VAULT_KEY/u.test(key) && value) {
          assert.equal(output.includes(value), false, `JSON exposed ${key}`);
        }
      }
    }
  }
  function fixture(name) {
    const project = join(temporary, name);
    mkdirSync(project);
    command([
      "bootstrap",
      project,
      "--skills",
      "manual",
      "--image",
      "ghcr.io/upmaru/tama:0.13.2-server",
    ]);
    const composePath = join(project, "tama/compose.yaml");
    const model = parse(readFileSync(composePath, "utf8"));
    const identity = `tama-env-${randomUUID()}`;
    // Scope both the source and normalized name; recovery probes both names.
    model.services["tama-postgres"].volumes = runtime
      ? [`${identity}:/var/lib/postgresql/data`]
      : [];
    model.volumes = runtime ? { [identity]: { name: identity } } : {};
    writeFileSync(
      composePath,
      `# Generated by Tama Kit. Project-owned; edit directly.\n${stringify(model)}`,
    );
    const rootPath = join(project, "compose.yaml");
    const rootModel = parse(readFileSync(rootPath, "utf8"));
    rootModel.name = identity;
    writeFileSync(
      rootPath,
      `# Generated by Tama Kit. Application services may be added alongside this include.\n${stringify(rootModel)}`,
    );
    return { project, identity };
  }
  function recover(project, paths, flags = []) {
    for (const path of paths) rmSync(join(project, path));
    const diagnosis = preserve(project, () => env(project, "doctor", flags, 4));
    assert.deepEqual(
      diagnosis.files
        .filter((file) => file.status === "missing")
        .map((file) => file.relative)
        .sort(),
      [...paths].sort(),
    );
    const preview = preserve(project, () => env(project, "init", [...flags, "--dry-run"]));
    assert.equal(
      preview.files.some((file) => file.created),
      false,
    );
    const before = snapshot(project);
    const recovered = env(project, "init", flags);
    assert.deepEqual(
      recovered.files
        .filter((file) => file.created)
        .map((file) => file.relative)
        .sort(),
      [...paths].sort(),
    );
    assert.deepEqual(
      snapshot(project).filter((file) => before.some((old) => old.path === file.path)),
      before,
    );
    for (const path of paths) assert.equal(statSync(join(project, path)).mode & 0o777, 0o600);
    const healthy = preserve(project, () => env(project, "doctor", flags));
    const repeat = preserve(project, () => env(project, "init", flags));
    assert.equal(
      repeat.files.some((file) => file.created),
      false,
    );
    for (const document of [diagnosis, preview, recovered, healthy, repeat])
      noSecrets(project, paths, document);
    return recovered;
  }

  if (runtime) docker(["info", "--format", "{{.ServerVersion}}"]);
  const corePaths = ["tama/.tama.env", "tama/.tama.postgres.env"];
  const { project } = fixture("env-standard");
  const originalCore = snapshot(project).find((file) => file.path.endsWith("/.tama.env"));
  const derived = recover(project, [corePaths[1]]);
  assert.equal(derived.persistence.status, "not-required");
  assert.deepEqual(
    snapshot(project).find((file) => file.path === originalCore.path),
    originalCore,
  );
  if (!runtime) {
    rmSync(join(project, corePaths[0]));
    const blocked = preserve(project, () => env(project, "init", [], 4));
    assert.equal(blocked.persistence.status, "unknown");
    assert.equal(existsSync(join(project, corePaths[0])), false);
    // Restore only this disposable fixture so recover() can remove a complete pair.
    env(project, "init", ["--fresh"]);
  }
  const recovered = recover(project, corePaths, runtime ? [] : ["--fresh"]);
  assert.equal(recovered.persistence.status, runtime ? "absent" : "unknown");
  const core = values(project, corePaths[0]);
  const postgres = values(project, corePaths[1]);
  const database = new URL(core.DATABASE_URL);
  assert.equal(decodeURIComponent(database.password) === postgres.POSTGRES_PASSWORD, true);
  assert.equal(decodeURIComponent(database.username) === postgres.POSTGRES_USER, true);
  assert.equal(database.pathname.slice(1) === postgres.POSTGRES_DB, true);

  const additive = fixture("env-mcp-app");
  command([
    "generate",
    "mcp-app",
    additive.project,
    "--provider-name",
    "fixture",
    "--provider-origin",
    "http://host.docker.internal:4100",
    "--allowed-origin",
    "http://localhost:4000",
  ]);
  const flags = ["--compose", "compose.yaml", "--compose", "tama/compose.mcp-app.yaml", "--fresh"];
  const integrationPaths = ["tama/.mcp-app.env", "tama/.fixture.integration.env"];
  recover(additive.project, [...corePaths, ...integrationPaths], flags);
  assert.equal(values(additive.project, integrationPaths[0]).TAMA_MCP_APP_MODE, "prepared");
  assert.equal(values(additive.project, integrationPaths[1]).FIXTURE_TAMA_MCP_APP_MODE, "prepared");
  const tamaKey = values(
    additive.project,
    integrationPaths[0],
  ).TAMA_MCP_APP_INTROSPECTION_PRIVATE_KEY;
  const providerKey = values(
    additive.project,
    integrationPaths[1],
  ).FIXTURE_OAUTH_PRIVATE_SIGNING_KEY;
  assert.ok(
    tamaKey && providerKey && tamaKey !== providerKey,
    "integration keys must be independent",
  );

  if (runtime) {
    for (const [fixtureProject, missing, selection] of [
      [project, corePaths, []],
      [additive.project, integrationPaths, flags],
    ]) {
      const compose = ["compose", "-f", join(fixtureProject, "compose.yaml")];
      const identity = parse(readFileSync(join(fixtureProject, "compose.yaml"), "utf8")).name;
      try {
        docker(
          [...compose, "up", "-d", "--wait", "--wait-timeout", "90", "tama-postgres"],
          fixtureProject,
        );
        const sql = (query) =>
          docker(
            [
              ...compose,
              "exec",
              "-T",
              "tama-postgres",
              "sh",
              "-c",
              'exec psql -U "$POSTGRES_USER" -d "$POSTGRES_DB" -Atc "$1"',
              "sh",
              query,
            ],
            fixtureProject,
          );
        sql(
          "CREATE TABLE recovery_acceptance (value text); INSERT INTO recovery_acceptance VALUES ('preserved');",
        );
        const container = docker(
          [...compose, "ps", "-q", "--no-trunc", "tama-postgres"],
          fixtureProject,
        );
        assert.ok(container, "acceptance database container is missing");
        const companion = recover(fixtureProject, [corePaths[1]], selection);
        assert.equal(companion.persistence.status, "not-required");
        assert.equal(sql("SELECT value FROM recovery_acceptance;"), "preserved");
        for (const path of missing) rmSync(join(fixtureProject, path));
        for (const fresh of [false, true]) {
          const selected = selection.filter((flag) => flag !== "--fresh");
          const refused = preserve(fixtureProject, () =>
            env(fixtureProject, "init", [...selected, ...(fresh ? ["--fresh"] : [])], 4),
          );
          assert.equal(refused.persistence.status, "detected");
          for (const path of missing) assert.equal(existsSync(join(fixtureProject, path)), false);
        }
        // exec needs existing env files for Compose parsing; container ID does not.
        assert.equal(
          docker(
            [
              "exec",
              container,
              "sh",
              "-c",
              'exec psql -U "$POSTGRES_USER" -d "$POSTGRES_DB" -Atc "$1"',
              "sh",
              "SELECT value FROM recovery_acceptance;",
            ],
            fixtureProject,
          ),
          "preserved",
        );
        // Prove the volume itself blocks issuance after all service containers are gone.
        docker(["rm", "-f", container]);
        const volumeOnly = preserve(fixtureProject, () =>
          env(
            fixtureProject,
            "init",
            [...selection.filter((flag) => flag !== "--fresh"), "--fresh"],
            4,
          ),
        );
        assert.equal(volumeOnly.persistence.status, "detected");
        assert.match(volumeOnly.persistence.detail, /local volume/u);
        for (const path of missing) assert.equal(existsSync(join(fixtureProject, path)), false);
      } finally {
        // Missing env files cannot prevent cleanup of this uniquely named fixture.
        const ids = docker([
          "ps",
          "-aq",
          "--filter",
          `label=com.docker.compose.project=${identity}`,
        ]);
        if (ids) docker(["rm", "-f", ...ids.split(/\s+/u)]);
        if (execute("docker", ["volume", "inspect", identity]).status === 0)
          docker(["volume", "rm", identity]);
        const networks = docker([
          "network",
          "ls",
          "-q",
          "--filter",
          `label=com.docker.compose.project=${identity}`,
        ]);
        if (networks) docker(["network", "rm", ...networks.split(/\s+/u)]);
      }
    }
  }
  return runtime
    ? "real Docker recovery and persisted-database refusal"
    : "installed env doctor/init recovery";
}
